package vn.nhom17.banhang.platform;

import java.util.UUID;
import org.springframework.web.multipart.MultipartFile;

/** Durable, bounded file hand-off between the HTTP process and the file-command worker. */
public interface BackofficeFileStore {
    long MAX_FILE_BYTES = 2L * 1024 * 1024;

    Reference stage(String action, UUID requestKey, MultipartFile upload);

    Content read(String action, Reference reference);

    /** Release only after the surrounding worker transaction has committed its durable terminal result. */
    void discardAfterCommit(String action, Reference reference);

    /** Opaque key generated by the server; no client supplied filesystem paths are accepted. */
    record Reference(String key, UUID storeId, UUID userId, String action, UUID requestKey,
                     String sha256, long size, String filename) {}

    record Content(byte[] bytes, String filename) {}
}
