#!/bin/sh
set -eu
: "${DB_WAREHOUSE_WRITER_PASSWORD:?Set DB_WAREHOUSE_WRITER_PASSWORD}"
: "${DB_WAREHOUSE_READER_PASSWORD:?Set DB_WAREHOUSE_READER_PASSWORD}"
psql --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" --set ON_ERROR_STOP=1 \
  --set writer_password="$DB_WAREHOUSE_WRITER_PASSWORD" \
  --set reader_password="$DB_WAREHOUSE_READER_PASSWORD" <<'SQL'
CREATE ROLE warehouse_writer LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS PASSWORD :'writer_password';
CREATE ROLE warehouse_reader LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS PASSWORD :'reader_password';
ALTER ROLE warehouse_reader SET default_transaction_read_only = on;
SQL
